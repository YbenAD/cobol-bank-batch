-- ---------------------------------------------------------------------
-- TABLE D'HISTORIQUE DES MOUVEMENTS APPLIQUES (CHARGEE PAR BNKDB201)
-- A EXECUTER VIA SPUFI, DSNTEP2 OU L'EXTENSION DB2 DE VS CODE.
-- SANS QUALIFIANT, LA TABLE EST CREEE DANS TON SCHEMA (TON ID),
-- QUI EST AUSSI LE QUALIFIER UTILISE AU BIND (JCL COMPDB2).
-- ---------------------------------------------------------------------
CREATE TABLE MVT_HIST
  ( REF_MVT        CHAR(12)       NOT NULL
  , NUM_CPT        CHAR(11)       NOT NULL
  , TYPE_MVT       CHAR(1)        NOT NULL
  , MONTANT        DECIMAL(11,2)  NOT NULL
  , DATE_MVT       DATE           NOT NULL
  , LIBELLE        CHAR(30)       NOT NULL
  , TS_CHARGEMENT  TIMESTAMP      NOT NULL
  , CONSTRAINT MVT_HIST_PK PRIMARY KEY (REF_MVT)
  , CONSTRAINT MVT_HIST_CK_TYPE CHECK (TYPE_MVT IN ('D', 'C'))
  );

-- INDEX UNIQUE OBLIGATOIRE POUR LA CLE PRIMAIRE (SINON TABLE INCOMPLETE)
CREATE UNIQUE INDEX MVT_HIST_IX1 ON MVT_HIST (REF_MVT);

-- INDEX DE CONSULTATION PAR COMPTE ET DATE
CREATE INDEX MVT_HIST_IX2 ON MVT_HIST (NUM_CPT, DATE_MVT);

COMMIT;

-- ---------------------------------------------------------------------
-- REQUETES DE VERIFICATION APRES EXECUTION DE LA CHAINE
-- ---------------------------------------------------------------------
-- NOMBRE DE MOUVEMENTS ET SOLDE NET PAR COMPTE
SELECT NUM_CPT
     , COUNT(*)                                            AS NB_MVT
     , SUM(CASE TYPE_MVT WHEN 'C' THEN MONTANT ELSE 0 END) AS CREDITS
     , SUM(CASE TYPE_MVT WHEN 'D' THEN MONTANT ELSE 0 END) AS DEBITS
  FROM MVT_HIST
 GROUP BY NUM_CPT
 ORDER BY NUM_CPT;

-- DERNIERS MOUVEMENTS D'UN COMPTE
SELECT REF_MVT, DATE_MVT, TYPE_MVT, MONTANT, LIBELLE
  FROM MVT_HIST
 WHERE NUM_CPT = '10000000001'
 ORDER BY DATE_MVT DESC, REF_MVT DESC
 FETCH FIRST 10 ROWS ONLY;
