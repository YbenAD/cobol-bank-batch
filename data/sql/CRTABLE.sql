-- ---------------------------------------------------------------------
-- TABLE D'HISTORIQUE DES MOUVEMENTS APPLIQUES (CHARGEE PAR BNKDB201)
--
-- A EXECUTER AVEC L'EXTENSION "IBM DB2 FOR Z/OS DEVELOPER EXTENSION"
-- DE VS CODE (SUR IBM Z XPLORE : LOCATION ZXPDB2, SOUS-SYSTEME DBDG).
--
-- AVANT EXECUTION : REMPLACER Z99999 PAR TON IDENTIFIANT.
-- SUR IBM Z XPLORE, UNE TABLE NE PEUT ETRE CREEE QUE DANS LA BASE DE
-- DONNEES QUI PORTE TON ID (SINON SQLCODE -551).
--
-- SANS QUALIFIANT, LA TABLE EST CREEE DANS TON SCHEMA (TON ID), QUI
-- EST AUSSI LE QUALIFIER UTILISE AU BIND (JCL COMPDB2).
--
-- L'INDEX UNIQUE DE LA CLE PRIMAIRE EST CREE AUTOMATIQUEMENT PAR DB2
-- (TABLESPACE CREE IMPLICITEMENT DANS LA BASE).
-- ---------------------------------------------------------------------

-- 1. CREATION DE LA TABLE
--    (SI ELLE EXISTE DEJA : EXECUTER D'ABORD  DROP TABLE MVT_HIST; )
CREATE TABLE MVT_HIST
  ( REF_MVT        CHAR(12)       NOT NULL
  , NUM_CPT        CHAR(11)       NOT NULL
  , TYPE_MVT       CHAR(1)        NOT NULL
  , MONTANT        DECIMAL(11,2)  NOT NULL
  , DATE_MVT       DATE           NOT NULL
  , LIBELLE        CHAR(30)       NOT NULL
  , TS_CHARGEMENT  TIMESTAMP      NOT NULL
  , CONSTRAINT MVT_HIST_PK PRIMARY KEY (REF_MVT)
  , CONSTRAINT MVT_HIST_CK_TYPE CHECK (TYPE_MVT IN ('D', 'C'))
  )
  IN DATABASE Z99999;

-- 2. INDEX DE CONSULTATION PAR COMPTE ET DATE (FACULTATIF)
CREATE INDEX MVT_HIST_IX2 ON MVT_HIST (NUM_CPT, DATE_MVT);

-- 3. VERIFICATION : LA TABLE EXISTE ET EST VIDE (RESULTAT ATTENDU : 0)
SELECT COUNT(*) AS NB_LIGNES FROM MVT_HIST;

-- ---------------------------------------------------------------------
-- REQUETES DE CONTROLE APRES EXECUTION DE LA CHAINE (OU DE LOADDB2)
-- ---------------------------------------------------------------------

-- 4. NOMBRE DE MOUVEMENTS ET TOTAUX PAR COMPTE (ATTENDU : 7 COMPTES,
--    11 MOUVEMENTS, 2 899,50 DE CREDITS ET 3 975,49 DE DEBITS AU TOTAL)
SELECT NUM_CPT
     , COUNT(*)                                            AS NB_MVT
     , SUM(CASE TYPE_MVT WHEN 'C' THEN MONTANT ELSE 0 END) AS CREDITS
     , SUM(CASE TYPE_MVT WHEN 'D' THEN MONTANT ELSE 0 END) AS DEBITS
  FROM MVT_HIST
 GROUP BY NUM_CPT
 ORDER BY NUM_CPT;

-- 5. DERNIERS MOUVEMENTS D'UN COMPTE
SELECT REF_MVT, DATE_MVT, TYPE_MVT, MONTANT, LIBELLE
  FROM MVT_HIST
 WHERE NUM_CPT = '10000000001'
 ORDER BY DATE_MVT DESC, REF_MVT DESC
 FETCH FIRST 10 ROWS ONLY;

